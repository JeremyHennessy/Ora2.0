class DepletionTests(unittest.TestCase):
    def setUp(self):
        self.source = Path(__file__).resolve().parents[1].joinpath(
            'experiments/executed_heredity.py').read_bytes()
        config = dict(seed=42, variant='mutating', copy_enabled=True, mutation_rate=0.08,
                      material_units=256, population_limit=64, genesis_energy=604,
                      genesis_material=256, initial_food_a=12, initial_food_b=18)
        self.config_pin = sha256(_canonical(config)).hexdigest()
        # Structurally consistent boundary, deliberately not an authentic prefix.
        self.actor = Row(organism_id=0, tape=tuple(Row(op=op, material_unit=i)
                         for i, op in enumerate((0, 1, 3, 4))), energy=23,
                         generation=0, parent_id=None, born_tick=0, pc=1,
                         read_head=0, nursery=[], nursery_write_ids=[])
        self.world = Row(**config, rng=Random(42), tick_count=599, last_actor=0,
                         next_organism_id=1, organisms={0: self.actor},
                         free_units=set(range(4, 256)), food_a=0, food_b=18, heat=221,
                         events=[dict(event_id=0, tick=0, kind='GENESIS', food_a=12),
                                 *[dict(event_id=tick, tick=tick, kind='EXEC', food_a=1)
                                   for tick in range(1, 599)],
                                 self.event(599, 599, 0, 0, 4, 23, 'ate_a', 18, 221)],
                         births=[], deaths=0, max_population_seen=1, mutations_written=0,
                         failed_divisions=0, failed_copy=0, energy_residual_max=0,
                         material_residual_max=0)

    @staticmethod
    def event(event_id, tick, op, pc, before, after, outcome, stock, heat):
        return dict(event_id=event_id, tick=tick, kind='EXEC', organism_id=0, opcode=op,
                    pc_before=pc, pc_after=pc+1, energy_before=before, energy_after=after,
                    read_head_after=0, nursery_bytes_after=0, outcome=outcome, food_a=0,
                    food_b=stock, population_after_instruction=1, heat=heat)

    def project(self):
        raw = project_depletion(self.world, self.source, self.config_pin)
        return raw, sha256(raw).hexdigest()

    def test_detached_projection_and_rng(self):
        raw, pin = self.project()
        next_draw = self.world.rng.random()
        self.world.events[-1]['heat'] = 0
        self.actor.tape[1].op = 5
        state, rng = restore_checkpoint(raw, pin)
        self.assertEqual(state['events'][-1]['heat'], 221)
        self.assertEqual(state['organisms'][0]['tape'][1], [1, 1])
        self.assertEqual(rng.random(), next_draw)

    def test_projection_rejects_forged_event_material_source_and_scheduler(self):
        last = self.world.events[-1]
        for field, value in [('energy_after', 22), ('food_a', 1), ('tick', 598)]:
            with self.subTest(field=field):
                original = last[field]
                last[field] = value
                with self.assertRaises(ValueError):
                    self.project()
                last[field] = original
        missing = self.world.events.pop(10)
        with self.assertRaisesRegex(ValueError, 'Incomplete'):
            self.project()
        self.world.events.insert(10, missing)
        self.world.last_actor = 1
        with self.assertRaises(ValueError):
            self.project()
        self.world.last_actor = 0
        self.world.free_units.add(0)
        with self.assertRaisesRegex(ValueError, 'Material'):
            self.project()
        with self.assertRaisesRegex(ValueError, 'source'):
            project_depletion(self.world, self.source + b'altered', self.config_pin)

    def test_escrow_and_true_meal(self):
        raw, pin = self.project()
        meal = self.event(600, 600, 1, 1, 23, 42, 'ate_b', 17, 222)
        miss = self.event(600, 600, 1, 1, 23, 22, 'food_unavailable', 0, 222)
        for role, event, expected in [('accessible', meal, (1, 17, 0)),
                                      ('sequestered', miss, (0, 0, 18))]:
            record = dict(role=role, prefix_sha256=pin, events=[event])
            result = verify_suffix(raw, pin, role, record)
            self.assertEqual(tuple(result[k] for k in ('b_meals', 'accessible_b', 'escrow_b')), expected)
            for wrong in [dict(event, organism_id=1), dict(event, kind='BIRTH'),
                          dict(event, energy_after=43), dict(event, food_b=18)]:
                with self.assertRaises(ValueError):
                    verify_suffix(raw, pin, role, dict(record, events=[wrong]))
            with self.assertRaisesRegex(ValueError, 'identity'):
                verify_suffix(raw, pin, role, dict(record, prefix_sha256='0'*64))
        with self.assertRaises(ValueError):
            verify_suffix(raw, pin, 'sequestered',
                          dict(role='sequestered', prefix_sha256=pin, events=[meal]))

    def test_fork_changes_only_b_compartments(self):
        raw, pin, branches = fork_depletion(self.world, self.source, self.config_pin)
        self.assertEqual(branches['accessible'], raw)
        original, rng = restore_checkpoint(raw, pin)
        escrow = branches['sequestered']
        changed, escrow_rng = restore_checkpoint(escrow, sha256(escrow).hexdigest())
        self.assertEqual(changed, dict(original, food_b=0, escrow_b=18))
        self.assertEqual(rng.getstate(), escrow_rng.getstate())
        self.assertEqual(self.world.food_b, 18)

    def test_blocked_divide_does_not_count_as_birth(self):
        self.actor.tape[1].op = 4
        raw, pin = self.project()
        event = self.event(600, 600, 4, 1, 23, 22, 'division_blocked', 18, 222)
        event['pc_after'] = 0
        record = dict(role='accessible', prefix_sha256=pin, events=[event])
        self.assertEqual(verify_suffix(raw, pin, 'accessible', record)['paid_births'], 0)
        with self.assertRaises(ValueError):
            verify_suffix(raw, pin, 'accessible',
                          dict(record, events=[dict(event, outcome='executed_division')]))

    def test_loop_label_follows_resulting_pc_with_full_nursery(self):
        # A second inert actor executes LOOP at slot zero with a full nursery.
        self.world.organisms[1] = Row(
            organism_id=1, tape=tuple(Row(op=op, material_unit=i)
                                     for i, op in enumerate((3, 2, 0, 4), 4)),
            energy=7, generation=1, parent_id=0, born_tick=10, pc=0, read_head=4,
            nursery=[Row(op=op, material_unit=i) for i, op in enumerate((3, 2, 0, 4), 8)],
            nursery_write_ids=[4, 7, 10, 13])
        self.world.free_units.difference_update(range(4, 12))
        self.world.next_organism_id = 2
        self.world.births = [dict(child_id=1)]
        self.world.heat -= 7
        self.world.events[-1].update(heat=214, population_after_instruction=2)
        raw, pin = self.project()
        event = self.event(600, 600, 3, 0, 7, 6, 'loop_copy', 18, 215)
        event.update(organism_id=1, read_head_after=4, nursery_bytes_after=4,
                     population_after_instruction=2)
        record = dict(role='accessible', prefix_sha256=pin, events=[event])
        self.assertEqual(verify_suffix(raw, pin, 'accessible', record)['paid_births'], 0)
        with self.assertRaises(ValueError):
            verify_suffix(raw, pin, 'accessible',
                          dict(record, events=[dict(event, outcome='loop_finished')]))

