    def test_lawful_pair_and_corruption(self):
        from copy import deepcopy

        def records(rows):
            return [dict(zip(_PAIR_COLUMNS[row[0]], deepcopy(row[1:]), strict=True))
                    for row in rows]

        fixture = deepcopy(_PAIR_STATE)
        actors = fixture.pop('organisms')
        for actor in actors:
            for field in ('tape', 'nursery'):
                actor[field] = [Row(op=op, material_unit=unit) for op, unit in actor[field]]
        fixture.update(organisms={a['organism_id']: Row(**a) for a in actors},
                       events=records(_PAIR_PREFIX), births=records(_PAIR_BIRTHS))
        rng = Random(42)
        for _ in range(31):
            if rng.random() < 0.08:
                rng.randrange(5)
        config = dict(seed=42, variant='mutating', copy_enabled=True, mutation_rate=0.08,
                      material_units=256, population_limit=64, genesis_energy=604,
                      genesis_material=256, initial_food_a=12, initial_food_b=18)
        raw, pin, starts = fork_depletion(
            Row(**config, **fixture, rng=rng), self.source, self.config_pin)
        self.assertEqual(starts['accessible'], raw)
        sequestered = starts['sequestered']
        start, fork_rng = restore_checkpoint(sequestered, sha256(sequestered).hexdigest())
        original, _ = restore_checkpoint(raw, pin)
        self.assertEqual(start, dict(original, food_b=0, escrow_b=10))
        self.assertEqual(fork_rng.getstate(), rng.getstate())
        branches = {role: dict(role=role, prefix_sha256=pin, events=records(rows))
                    for role, rows in [('accessible', _PAIR_ACCESSIBLE),
                                       ('sequestered', _PAIR_SEQUESTERED)]}
        result = verify_pair(42, raw, pin, branches)
        self.assertEqual(result['contrast'], 3)
        for role, meals, escrow, births in [('accessible', 10, 0, 9),
                                             ('sequestered', 0, 10, 6)]:
            verified = result['branches'][role]
            self.assertEqual(verified, dict(paid_births=births, b_meals=meals,
                             accessible_b=0, escrow_b=escrow, extinct=True,
                             authenticated_execution=False))
        forged = deepcopy(branches)
        write = next(e for e in forged['accessible']['events'] if e['kind'] == 'COPY_WRITE')
        write['material_unit'] += 1
        with self.assertRaisesRegex(ValueError, rf"{write['event_id']} \(COPY_WRITE\)"):
            verify_pair(42, raw, pin, forged)
        panel = [dict(index=i, raw=raw, pin=pin, branches=branches) for i in range(128)]
        self.assertEqual(verify_panel([42]*128, panel), [result]*128)
        with self.assertRaisesRegex(ValueError, '128'):
            verify_panel([42]*128, panel[:-1])
        with self.assertRaisesRegex(ValueError, 'context record'):
            verify_panel([42]*128, panel[:1]+panel[:-1])


